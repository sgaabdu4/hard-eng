"""Guarded cleanup of a task worktree that holds initialized submodules."""

from collections.abc import Callable
from dataclasses import replace
from pathlib import Path

import pytest
import ship_actions
from shipping import Shipment, git


def _with_submodule(shipment: Shipment, tmp_path: Path) -> Shipment:
    module = tmp_path / "module"
    git(tmp_path, "init", "-q", str(module))
    git(module, "config", "user.name", "Ship Fixture")
    git(module, "config", "user.email", "ship-fixture@example.test")
    (module / "work.txt").write_text("baseline")
    git(module, "add", "work.txt")
    git(module, "commit", "-qm", "module baseline")
    allow = ("-c", "protocol.file.allow=always")
    git(shipment.root, *allow, "submodule", "add", "-q", str(module), "component")
    git(shipment.root, "commit", "-qm", "include module")
    git(shipment.root, "push", "-q", "origin", shipment.branch)
    head = git(shipment.root, "rev-parse", "HEAD").strip()
    return replace(shipment, head_sha=head)


def _edit_file(inner: Path) -> None:
    (inner / "work.txt").write_text("valuable nested work")


def _ignored_file(inner: Path) -> None:
    exclude = Path(git(inner, "rev-parse", "--git-path", "info/exclude").strip())
    (inner / exclude).parent.mkdir(parents=True, exist_ok=True)
    (inner / exclude).write_text("*.log\n")
    (inner / "build.log").write_text("generated by the task")


def _local_branch_commit(inner: Path) -> None:
    recorded = git(inner, "rev-parse", "HEAD").strip()
    git(inner, "config", "user.name", "Ship Fixture")
    git(inner, "config", "user.email", "ship-fixture@example.test")
    git(inner, "checkout", "-qb", "scratch")
    (inner / "work.txt").write_text("kept only on a local branch")
    git(inner, "commit", "-qam", "unpushed nested work")
    git(inner, "checkout", "-q", "--detach", recorded)


def _stash(inner: Path) -> None:
    git(inner, "config", "user.name", "Ship Fixture")
    git(inner, "config", "user.email", "ship-fixture@example.test")
    (inner / "work.txt").write_text("kept only in a stash")
    git(inner, "stash", "push", "-q")


@pytest.mark.parametrize(
    "work",
    [_edit_file, _ignored_file, _local_branch_commit, _stash],
    ids=["edited file", "ignored file", "unpushed local branch", "stash"],
)
def test_cleanup_preserves_work_that_only_the_submodule_holds(
    delivered_worktree: tuple[Path, Shipment],
    tmp_path: Path,
    work: Callable[[Path], None],
) -> None:
    root, shipment = delivered_worktree
    shipment = _with_submodule(shipment, tmp_path)
    git(shipment.root, "config", "diff.ignoreSubmodules", "all")
    work(shipment.root / "component")
    with pytest.raises(ValueError, match="modified, untracked or ignored|component"):
        ship_actions.cleanup(root, shipment)
    assert (shipment.root / "component").is_dir()
    assert ship_actions.remote_branch(root, "origin", shipment.branch) == (
        shipment.head_sha
    )


def test_cleanup_preserves_a_submodule_moved_off_the_recorded_commit(
    delivered_worktree: tuple[Path, Shipment], tmp_path: Path
) -> None:
    root, shipment = delivered_worktree
    shipment = _with_submodule(shipment, tmp_path)
    inner = shipment.root / "component"
    git(inner, "config", "user.name", "Ship Fixture")
    git(inner, "config", "user.email", "ship-fixture@example.test")
    git(inner, "commit", "--allow-empty", "-qm", "detached nested work")
    with pytest.raises(ValueError, match="component"):
        ship_actions.cleanup(root, shipment)
    assert inner.is_dir()


@pytest.mark.parametrize("initialized", [True, False], ids=["initialized", "not"])
def test_cleanup_removes_task_whose_submodule_holds_nothing_else(
    delivered_worktree: tuple[Path, Shipment], tmp_path: Path, initialized: bool
) -> None:
    root, shipment = delivered_worktree
    shipment = _with_submodule(shipment, tmp_path)
    if not initialized:
        git(shipment.root, "submodule", "deinit", "-q", "-f", "component")
    assert git(shipment.root, "submodule", "status").startswith("-") is not initialized
    ship_actions.cleanup(root, shipment)
    assert not shipment.root.exists()
    assert git(root, "branch", "--list", shipment.branch).strip() == ""
    assert ship_actions.remote_branch(root, shipment.remote, shipment.branch) is None


def test_cleanup_removes_task_whose_shallow_submodule_has_no_remote_branch_ref(
    delivered_worktree: tuple[Path, Shipment], tmp_path: Path
) -> None:
    root, shipment = delivered_worktree
    shipment = _with_submodule(shipment, tmp_path)
    inner = shipment.root / "component"
    for line in git(inner, "for-each-ref", "refs/remotes", "refs/heads").splitlines():
        git(inner, "update-ref", "-d", line.split()[-1])
    assert git(inner, "for-each-ref", "refs/remotes", "refs/heads").strip() == ""
    ship_actions.cleanup(root, shipment)
    assert not shipment.root.exists()
